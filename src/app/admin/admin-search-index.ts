export type AdminSearchHit = {
  key: string;
  section: string;
  group: string;
  label: string;
  kind: 'section' | 'field';
};

type SearchableGroup = {
  title: string;
  items: { key: string; title: string }[];
};

const normalize = (value: string) => value.trim().toLowerCase();

export function searchAdminItems(groups: SearchableGroup[], query: string, limit = 20): AdminSearchHit[] {
  const q = normalize(query);
  if (!q) return [];
  const hits: Array<AdminSearchHit & { rank: number }> = [];
  for (const group of groups) {
    const groupHit = normalize(group.title).includes(q);
    for (const item of group.items) {
      const title = normalize(item.title);
      if (title.includes(q)) {
        hits.push({ key: item.key, section: item.title, group: group.title, label: item.title, kind: 'section', rank: title.startsWith(q) ? 0 : 1 });
      } else if (groupHit) {
        hits.push({ key: item.key, section: item.title, group: group.title, label: item.title, kind: 'section', rank: 4 });
      }
      for (const field of adminSearchFields[item.key] || []) {
        const name = normalize(field);
        if (!name.includes(q)) continue;
        hits.push({ key: item.key, section: item.title, group: group.title, label: field, kind: 'field', rank: name.startsWith(q) ? 2 : 3 });
      }
    }
  }
  hits.sort((a, b) => a.rank - b.rank || a.label.length - b.label.length);
  return hits.slice(0, limit).map((hit) => ({
    key: hit.key,
    section: hit.section,
    group: hit.group,
    label: hit.label,
    kind: hit.kind,
  }));
}

export function splitAdminQuery(text: string, query: string) {
  const q = query.trim();
  const index = q ? text.toLowerCase().indexOf(q.toLowerCase()) : -1;
  if (index < 0) return null;
  return { before: text.slice(0, index), match: text.slice(index, index + q.length), after: text.slice(index + q.length) };
}
